#!/usr/bin/env node
// Refresh the Media Studio tool allowlist from the server's GA contract snapshot.
//
// The Media Studio pages under guide/media-studio/ are hand-written, but the set
// of tools they may name is not a matter of prose — it is the GA contract of
// pa-media-tools-mcp-server. That contract lives in another repo, and CI only
// ever checks out this one, so the names are committed here as data and
// check-counts.mjs diffs the pages against them.
//
// Run this (not CI) whenever the server's GA tool set changes:
//
//   node scripts/export-media-tools.mjs \
//     ~/pa-media-tools-mcp-server/server/src/core/service/mcp/__contract__/mcp-contract.snapshot.json
//
// Then re-run `npm run check:counts` and update the pages until it passes.
// Bumping this file is deliberately a human step: a tool appearing or
// disappearing on a published connector surface is never a silent change.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const snapshotPath = process.argv[2]
if (!snapshotPath) {
  console.error('usage: node scripts/export-media-tools.mjs <path-to-mcp-contract.snapshot.json>')
  process.exit(1)
}

const snapshot = JSON.parse(readFileSync(snapshotPath, 'utf8'))
if (!Array.isArray(snapshot)) {
  console.error(`✗ ${snapshotPath} is not a tool array — is that the GA contract snapshot?`)
  process.exit(1)
}

const tools = snapshot.map((t) => t.name).sort()
const unexpected = tools.filter((n) => !n.startsWith('picsart_media_'))
if (unexpected.length) {
  console.error(`✗ unexpected tool names in snapshot: ${unexpected.join(', ')}`)
  process.exit(1)
}

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', '.vitepress', 'theme', 'data', 'media-tools.json')
const payload = {
  _comment: 'Generated by scripts/export-media-tools.mjs from pa-media-tools-mcp-server. Do not hand-edit.',
  channel: 'ga',
  tools,
}
writeFileSync(out, `${JSON.stringify(payload, null, 2)}\n`)
console.log(`✓ wrote ${tools.length} GA tool names to .vitepress/theme/data/media-tools.json`)
